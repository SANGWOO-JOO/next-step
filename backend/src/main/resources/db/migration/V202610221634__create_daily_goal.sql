-- 1-2a 하루 목표. 주간 목표에 연결되고, 날짜는 그 주간 목표의 주(월~일) 안이어야 한다.
-- 핵심(CORE)은 하루 최대 3개(서비스에서 검사). carry_count는 다른 날로 넘긴 횟수.
CREATE TABLE daily_goal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekly_goal_id BIGINT                   NOT NULL REFERENCES weekly_goal (id),
    goal_date      DATE                     NOT NULL,
    content        VARCHAR(500)             NOT NULL,
    first_action   VARCHAR(500),
    category_id    BIGINT REFERENCES category (id),
    goal_type      VARCHAR(10)              NOT NULL,
    sort_order     INT                      NOT NULL,
    status         VARCHAR(10)              NOT NULL,
    carry_count    INT                      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_daily_goal_date ON daily_goal (goal_date);
CREATE INDEX ix_daily_goal_weekly_goal ON daily_goal (weekly_goal_id);

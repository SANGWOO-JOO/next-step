-- 목표마다 주별 목표 시간(분). 지난 주 계획과 실제를 비교하려고 주마다 따로 둔다
CREATE TABLE goal_week (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT  NOT NULL REFERENCES app_user (id),
    goal_id    BIGINT  NOT NULL REFERENCES goal (id) ON DELETE CASCADE,
    week_start DATE    NOT NULL,
    minutes    INT     NOT NULL,
    CONSTRAINT uq_goal_week UNIQUE (goal_id, week_start),
    CONSTRAINT ck_goal_week_minutes CHECK (minutes >= 0)
);
CREATE INDEX ix_goal_week_user_week ON goal_week (user_id, week_start);


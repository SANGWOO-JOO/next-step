-- 1-4e 실제 기록: 그 시간에 실제로 한 일. 계획(time_block)과 나란히 비교한다.
-- 같은 날 기록끼리 겹치지 않는 규칙(새 기록 우선으로 자르기·나누기)과 붙어 있는 같은 기록 합치기는 서비스에서 한다.
-- time_block_id는 [계획대로]로 만든 원래 계획 블록(참고용, 블록을 지워도 남도록 FK 없음).
CREATE TABLE actual_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_date       DATE                     NOT NULL,
    start_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    kind           VARCHAR(20)              NOT NULL,
    daily_goal_id  BIGINT REFERENCES daily_goal (id) ON DELETE SET NULL,
    category_id    BIGINT REFERENCES category (id),
    title          VARCHAR(100),
    time_block_id  BIGINT,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_actual_log_period CHECK (end_at > start_at)
);
CREATE INDEX ix_actual_log_date ON actual_log (log_date);
CREATE INDEX ix_actual_log_daily_goal ON actual_log (daily_goal_id);

-- 1-2b 집중 모드. 하루 목표 없이 분류만으로 시작할 수 있어 daily_goal_id는 비어 있을 수 있다.
-- 하루 목표를 지워도 집중 기록은 남기도록 ON DELETE SET NULL. 진행 중 세션 1개 규칙은 서비스에서 검사한다.
-- session_date는 시작 시각의 서울 기준 날짜. focus_seconds는 종료할 때 계산해 저장한다.
CREATE TABLE focus_session (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_goal_id  BIGINT REFERENCES daily_goal (id) ON DELETE SET NULL,
    category_id    BIGINT REFERENCES category (id),
    session_date   DATE                     NOT NULL,
    started_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at       TIMESTAMP WITH TIME ZONE,
    focus_minutes  INT                      NOT NULL,
    break_minutes  INT                      NOT NULL,
    focus_seconds  BIGINT,
    result         VARCHAR(20),
    source         VARCHAR(20)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_focus_session_date ON focus_session (session_date);
CREATE INDEX ix_focus_session_daily_goal ON focus_session (daily_goal_id);

-- 중단. type은 끝낼 때 정해진다(열린 동안은 NULL). 한 세션에 열린 중단은 1개(서비스에서 검사).
CREATE TABLE interruption (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    focus_session_id BIGINT                   NOT NULL REFERENCES focus_session (id) ON DELETE CASCADE,
    started_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at         TIMESTAMP WITH TIME ZONE,
    interruption_type VARCHAR(20),
    detection        VARCHAR(20)              NOT NULL,
    memo             VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_interruption_session ON interruption (focus_session_id);

-- 딴생각 메모. 집중 중 떠오른 생각을 적어 두고 나중에 확인한다.
CREATE TABLE distraction_note (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    focus_session_id BIGINT                   NOT NULL REFERENCES focus_session (id) ON DELETE CASCADE,
    content          VARCHAR(500)             NOT NULL,
    checked          BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_distraction_note_session ON distraction_note (focus_session_id);
CREATE INDEX ix_distraction_note_checked ON distraction_note (checked);

-- 1-1 목표 구조: 최종 목표 → 월간 목표 → 주간 목표. 하위 목표는 반드시 상위 목표에 연결된다.
CREATE TABLE goal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200)             NOT NULL,
    description VARCHAR(2000),
    start_date  DATE                     NOT NULL,
    target_date DATE                     NOT NULL,
    status      VARCHAR(20)              NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_goal_period CHECK (target_date >= start_date)
);

-- month_start: 해당 월의 1일
CREATE TABLE monthly_goal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id       BIGINT                   NOT NULL REFERENCES goal (id),
    month_start   DATE                     NOT NULL,
    content       VARCHAR(500)             NOT NULL,
    target_value  NUMERIC(12, 2),
    current_value NUMERIC(12, 2),
    unit          VARCHAR(20),
    achieved      BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_monthly_goal_goal ON monthly_goal (goal_id);
CREATE INDEX ix_monthly_goal_month ON monthly_goal (month_start);

-- week_start: 해당 주의 월요일
CREATE TABLE weekly_goal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monthly_goal_id BIGINT                   NOT NULL REFERENCES monthly_goal (id),
    week_start      DATE                     NOT NULL,
    content         VARCHAR(500)             NOT NULL,
    category_id     BIGINT REFERENCES category (id),
    achieved        BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_weekly_goal_monthly_goal ON weekly_goal (monthly_goal_id);
CREATE INDEX ix_weekly_goal_week ON weekly_goal (week_start);

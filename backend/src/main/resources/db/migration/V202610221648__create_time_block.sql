-- 1-2b 시간 블록: 하루 목표를 언제 할지. block_date는 시작 시각의 서울 기준 날짜(하루 목표의 날짜와 같음).
-- 같은 날 블록끼리 겹치지 않는 규칙은 서비스에서 검사한다.
CREATE TABLE time_block (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_goal_id BIGINT                   NOT NULL REFERENCES daily_goal (id),
    block_date    DATE                     NOT NULL,
    start_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_time_block_period CHECK (end_at > start_at)
);
CREATE INDEX ix_time_block_date ON time_block (block_date);
CREATE INDEX ix_time_block_daily_goal ON time_block (daily_goal_id);

-- 1-3a 주간 계획: 주간 목표를 요일별 작업으로 나눈다. plan_date는 주간 목표의 주(월~일) 안.
CREATE TABLE weekly_plan (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekly_goal_id BIGINT                   NOT NULL REFERENCES weekly_goal (id) ON DELETE CASCADE,
    plan_date      DATE                     NOT NULL,
    content        VARCHAR(500)             NOT NULL,
    sort_order     INT                      NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_weekly_plan_date ON weekly_plan (plan_date);
CREATE INDEX ix_weekly_plan_weekly_goal ON weekly_plan (weekly_goal_id);

-- 타이머 없이 한 공부(책, 오프라인 스터디 등)
CREATE TABLE manual_study_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_date    DATE                     NOT NULL,
    category_id BIGINT                   NOT NULL REFERENCES category (id),
    minutes     INT                      NOT NULL,
    memo        VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_manual_study_log_minutes CHECK (minutes BETWEEN 1 AND 600)
);
CREATE INDEX ix_manual_study_log_date ON manual_study_log (log_date);

-- 하루 기록. 날짜당 1개. 집중·딴짓 시간은 저장하지 않고 조회할 때 계산한다.
CREATE TABLE daily_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_date   DATE                     NOT NULL,
    memo       VARCHAR(2000),
    condition_score INT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_daily_log_date UNIQUE (log_date),
    CONSTRAINT ck_daily_log_condition CHECK (condition_score BETWEEN 1 AND 5)
);

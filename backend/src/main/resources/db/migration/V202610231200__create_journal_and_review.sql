-- 1-3b 주간 일지(주당 1개)와 월간 회고(월당 1개). ai_summary는 2단계에서 채운다.
CREATE TABLE weekly_journal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_start   DATE                     NOT NULL,
    good         VARCHAR(2000),
    bad          VARCHAR(2000),
    next_action  VARCHAR(2000),
    ai_summary   VARCHAR(4000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_weekly_journal_week UNIQUE (week_start)
);

CREATE TABLE monthly_review (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month_start   DATE                     NOT NULL,
    review        VARCHAR(4000),
    next_direction VARCHAR(2000),
    ai_summary    VARCHAR(4000),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_monthly_review_month UNIQUE (month_start)
);
